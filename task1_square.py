# 1 тапсырма. Қарапайым функция
# Санның квадратын қайтаратын square(number) функциясын жазыңыз.
# Функцияны 5, 0 және -4 аргументтерімен шақырыңыз.


def square(number):
    """Санның квадратын қайтарады."""
    return number * number


print(square(5))   # 25
print(square(0))   # 0
print(square(-4))  # 16
